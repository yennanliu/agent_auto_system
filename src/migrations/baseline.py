"""The frozen baseline schema — what every database looked like when Alembic was adopted.

This is deliberately **not** derived from ``src.models``: the models keep moving,
the baseline never does. It is used three ways, so they cannot disagree:

* the baseline revision (``versions/0001_baseline.py``) builds a fresh database from it;
* the legacy bootstrap creates any baseline table an old database is still missing;
* ``schema_drift()`` verifies a legacy database against it before it is stamped.

Do not edit this file to change the schema — add a new Alembic revision instead.
"""

