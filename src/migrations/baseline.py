def _family(type_: sa.types.TypeEngine) -> str:
    """Coarse type family. The legacy ALTERs declared booleans as INTEGER and floats
    as REAL, so an exact type comparison would reject every real legacy database."""
    if isinstance(type_, sa.Boolean | sa.Integer):
        return "integer"
    if isinstance(type_, sa.Numeric):  # Float / REAL / DOUBLE are Numeric subclasses
        return "number"
    if isinstance(type_, sa.DateTime):
        return "datetime"
    if isinstance(type_, sa.String):
        return "string"
    return type(type_).__name__.lower()


def schema_drift(conn: sa.Connection) -> list[str]:
    """Differences between the live schema and the baseline, as human-readable lines.

    Empty list = the database is exactly what the baseline revision describes, as far
    as later revisions can care: same tables, same column names, compatible column
    types, same named indexes. Tables the baseline does not know are ignored (they are
    not ours). Nullability, defaults and foreign keys of columns added by the legacy
    ALTERs are *not* compared — SQLite cannot change them in place and they are known
    to be looser than the baseline's.
    """
    insp = sa.inspect(conn)
    live_tables = set(insp.get_table_names())
    problems: list[str] = []
    for table in build_metadata().sorted_tables:
        if table.name not in live_tables:
            problems.append(f"table '{table.name}' is missing")
            continue
        live_cols = {c["name"]: c["type"] for c in insp.get_columns(table.name)}
        for col in table.columns:
            if col.name not in live_cols:
                problems.append(f"column '{table.name}.{col.name}' is missing")
            elif _family(live_cols[col.name]) != _family(col.type):
                problems.append(
                    f"column '{table.name}.{col.name}' has type {live_cols[col.name]!r}, "
                    f"expected a {_family(col.type)} type"
                )
        for extra in sorted(set(live_cols) - {c.name for c in table.columns}):
            problems.append(f"column '{table.name}.{extra}' is not part of the baseline schema")
        live_indexes = {ix["name"] for ix in insp.get_indexes(table.name)}
        for index in sorted(table.indexes, key=lambda ix: ix.name):
            if index.name not in live_indexes:
                problems.append(f"index '{index.name}' on '{table.name}' is missing")
    return problems
